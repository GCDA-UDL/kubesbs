# -*- coding: utf-8 -*-
"""Tables for the paper, as LaTeX fragments plus a plain-text summary.

  variability.tex  within-session spread (coefficient of variation of the runs
                   at each node count, median over node counts) and the
                   difference between the session means, per simulator.
  scaling.tex      cost-scaling exponent b of  metric = a * nodes^b  (least
                   squares on log-log over the pooled means) and its R^2.
  phases.tex       run time split into setup / workload / end-of-run check,
                   from harness logs (utils/repro/run_phases.py).
  summary.txt      the numbers quoted in the text.

Usage (from the repository root):
  python3 utils/repro/paper_tables.py --out tables-out \
    --session june=results-repro/big-all \
    --session oct=results-repro/big-spoofing-20261022,results-repro/big-spoofing-20261024 \
    --phases results-repro/big-spoofing-20261022/harness.log \
    --phases results-repro/big-spoofing-20261024/harness.log
LOG@sim1,sim2 keeps only those simulators from that log (e.g. to leave out
runs discarded in NOTES.md). Only points where the mean is >= 5 s (time) or >= 0.1 GB (memory) enter the
relative comparisons; below that the measurement resolution (1 s, 0.01 GB)
dominates.
"""
import argparse
import math
import os
import statistics as st
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sessions import load_sessions, pooled  # noqa: E402
import run_phases  # noqa: E402

ORDER = ["kcs", "opensim", "kwok", "kube-sched", "simkube", "kubemark"]
LABEL = {"kcs": "kcs", "opensim": "OpenSimulator", "kwok": "KWOK", "kube-sched": "KSS",
         "simkube": "SimKube", "kubemark": "Kubemark"}
COST = [("run_time", "Run time", 5), ("total_cpu_seconds", "CPU time", 5), ("memory_peak_gb", "Peak memory", 0.1)]


def cv(vals):
    m = st.mean(vals)
    return st.pstdev(vals) / m if m > 0 and len(vals) > 1 else None


def unsched_share(runs):
    return [r["unscheduled_pods"] / r["pod_count"] for r in runs if r["pod_count"] > 0]


def fit_power(ns, ys):
    xs = [math.log(n) for n in ns]
    ls = [math.log(y) for y in ys]
    mx, my = st.mean(xs), st.mean(ls)
    sxx = sum((x - mx) ** 2 for x in xs)
    b = sum((x - mx) * (y - my) for x, y in zip(xs, ls)) / sxx
    a = my - b * mx
    ss_res = sum((y - (a + b * x)) ** 2 for x, y in zip(xs, ls))
    ss_tot = sum((y - my) ** 2 for y in ls)
    return b, (1 - ss_res / ss_tot) if ss_tot > 0 else float("nan")


def fmt_range(vals, pct=True):
    if not vals:
        return "--"
    lo, hi = min(vals), max(vals)
    f = (lambda v: f"${v * 100:+.0f}$\\%") if pct else (lambda v: f"{v:.2f}")
    return f"{f(lo)} \\ldots {f(hi)}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--session", action="append", required=True)
    ap.add_argument("--phases", action="append", default=[])
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    sessions = load_sessions(a.session)
    data = pooled(sessions)
    lines = []

    # ---- variability
    rows = []
    for sim in ORDER:
        if sim not in data:
            continue
        cells = []
        for key, _, floor in COST:
            within = []
            for _, sdata in sessions:
                for n, runs in sdata.get(sim, {}).items():
                    vals = [r[key] for r in runs]
                    if st.mean(vals) >= floor and (c := cv(vals)) is not None:
                        within.append(c)
            between = []
            if len(sessions) == 2:
                (_, s1), (_, s2) = sessions
                for n in sorted(s1.get(sim, {})):
                    if n in s2.get(sim, {}):
                        m1 = st.mean(r[key] for r in s1[sim][n])
                        m2 = st.mean(r[key] for r in s2[sim][n])
                        if m1 >= floor:
                            between.append((m2 - m1) / m1)
            cells.append((st.median(within) if within else None, between))
        us = [x for runs in data[sim].values() for x in unsched_share(runs)]
        rows.append((sim, cells, max(us) if us else 0.0))
        lines.append(f"{sim}: within-CV median " +
                     ", ".join(f"{k}={c[0]:.1%}" if c[0] is not None else f"{k}=n/a"
                               for (k, _, _), c in zip(COST, cells)) +
                     " | between " + ", ".join(f"{k}=" + (f"{min(c[1]):+.0%}..{max(c[1]):+.0%}" if c[1] else "n/a")
                                               for (k, _, _), c in zip(COST, cells)))
    with open(os.path.join(a.out, "variability.tex"), "w", encoding="utf-8") as f:
        f.write("% generated by utils/repro/paper_tables.py\n\\begin{tabular}{lrrrlll}\n\\toprule\n")
        f.write(" & \\multicolumn{3}{c}{Within session (median CV)} & \\multicolumn{3}{c}{Between sessions (mean difference)}\\\\\n")
        f.write("\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\n")
        f.write("Simulator & Run time & CPU & Memory & Run time & CPU & Memory\\\\\n\\midrule\n")
        for sim, cells, _ in rows:
            w = [f"{c[0] * 100:.1f}\\%" if c[0] is not None else "--" for c in cells]
            b = [fmt_range(c[1]) for c in cells]
            f.write(f"{LABEL[sim]} & " + " & ".join(w + b) + "\\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")

    # ---- scaling exponents
    srows = []
    for sim in ORDER:
        if sim not in data:
            continue
        res = []
        for key, _, floor in COST:
            pts = [(n, st.mean(r[key] for r in runs)) for n, runs in sorted(data[sim].items())]
            pts = [(n, y) for n, y in pts if y >= floor]
            res.append(fit_power(*zip(*pts)) if len(pts) >= 4 else None)
        srows.append((sim, res))
        lines.append(f"{sim}: scaling b " + ", ".join(
            f"{k}={r[0]:.2f}(R2={r[1]:.2f})" if r else f"{k}=n/a" for (k, _, _), r in zip(COST, res)))
    with open(os.path.join(a.out, "scaling.tex"), "w", encoding="utf-8") as f:
        f.write("% generated by utils/repro/paper_tables.py\n\\begin{tabular}{lrrrrrr}\n\\toprule\n")
        f.write(" & \\multicolumn{2}{c}{Run time} & \\multicolumn{2}{c}{CPU time} & \\multicolumn{2}{c}{Peak memory}\\\\\n")
        f.write("\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\n")
        f.write("Simulator & $b$ & $R^2$ & $b$ & $R^2$ & $b$ & $R^2$\\\\\n\\midrule\n")
        for sim, res in srows:
            cells = []
            for r in res:
                cells += [f"{r[0]:.2f}", f"{r[1]:.2f}"] if r else ["--", "--"]
            f.write(f"{LABEL[sim]} & " + " & ".join(cells) + "\\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")

    # ---- run-time phases
    if a.phases:
        runs = []
        for spec in a.phases:
            path, _, keep = spec.partition("@")
            keep = set(keep.split(",")) if keep else None
            runs += [r | run_phases.phases(r) for r in run_phases.parse(path)
                     if keep is None or r["sim"] in keep]
        sizes = [100, 400, 800, 1200]
        with open(os.path.join(a.out, "phases.tex"), "w", encoding="utf-8") as f:
            f.write("% generated by utils/repro/paper_tables.py\n\\begin{tabular}{llrrrrr}\n\\toprule\n")
            f.write("Simulator & Nodes & Setup (s) & Workload (s) & End check (s) & Total (s) & End check\\\\\n\\midrule\n")
            for sim in ["kwok", "kube-sched", "simkube", "kubemark"]:
                for n in sizes:
                    g = [r for r in runs if r["sim"] == sim and r["nodes"] == n and r["total"] is not None]
                    if not g:
                        continue
                    m = {k: st.mean(r[k] for r in g) for k in ("setup", "workload", "end_check", "total")}
                    f.write(f"{LABEL[sim] if n == sizes[0] else ''} & {n} & {m['setup']:.0f} & {m['workload']:.0f} & "
                            f"{m['end_check']:.0f} & {m['total']:.0f} & {m['end_check'] / m['total']:.0%}\\\\\n".replace("%", "\\%"))
                    lines.append(f"phases {sim} {n}: setup {m['setup']:.0f} workload {m['workload']:.0f} "
                                 f"end {m['end_check']:.0f} total {m['total']:.0f} share {m['end_check'] / m['total']:.0%} (n={len(g)})")
                if sim != "kubemark":
                    f.write("\\addlinespace\n")
            f.write("\\bottomrule\n\\end{tabular}\n")

    # ---- numbers quoted in the text
    for sim in ORDER:
        if sim not in data:
            continue
        big = max(data[sim])
        for key, label, _ in COST:
            vals = [st.mean(r[key] for r in runs) for runs in data[sim].values()]
            at = st.mean(r[key] for r in data[sim][big])
            lines.append(f"{sim} {key}: mean at {big} nodes = {at:.2f}; range of means {min(vals):.2f}..{max(vals):.2f}")
        us = {n: st.mean(unsched_share(runs)) for n, runs in data[sim].items()}
        lines.append(f"{sim} unscheduled share by size: " + ", ".join(f"{n}:{v:.0%}" for n, v in sorted(us.items())))
    with open(os.path.join(a.out, "summary.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
